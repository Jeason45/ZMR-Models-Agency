async function createBlogPosts() {
  console.log('📝 Création des articles de blog...\n');

  try {
    for (const article of articles) {
      const existing = await prisma.blogPost.findUnique({
        where: { slug: article.slug }
      });

      if (existing) {
        console.log(`⏭️  Article "${article.title}" existe déjà`);
        continue;
      }

      const post = await prisma.blogPost.create({
        data: {
          ...article,
          publishedAt: new Date()
        }
      });

      console.log(`✅ Article créé: "${post.title}"`);
      console.log(`   → Slug: ${post.slug}`);
      console.log(`   → Catégorie: ${post.category}`);
      console.log(`   → Temps de lecture: ${post.readTime} min\n`);
    }

    console.log('🎉 Tous les articles ont été créés avec succès !');

    const count = await prisma.blogPost.count({ where: { published: true } });
    console.log(`\n📊 Total d'articles publiés: ${count}`);

  } catch (error) {
    console.error('❌ Erreur:', error);
  } finally {
    await prisma.$disconnect();
  }
}

createBlogPosts();
