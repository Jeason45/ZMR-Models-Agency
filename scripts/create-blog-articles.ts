async function createArticles() {
  console.log('🚀 Création des articles blog ZMR...\n');

  for (const article of articles) {
    try {
      console.log(`📝 Création de : "${article.title}"`);

      const response = await fetch('http://localhost:3000/api/blog', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(article),
      });

      if (response.ok) {
        const data = await response.json();
        console.log(`✅ Article créé avec succès (ID: ${data.id})`);
        console.log(`   URL: http://localhost:3000/blog/${data.slug}\n`);
      } else {
        const error = await response.json();
        console.error(`❌ Erreur: ${error.error}\n`);
      }
    } catch (error) {
      console.error(`❌ Erreur lors de la création de l'article:`, error, '\n');
    }
  }

  console.log('✨ Terminé! Rendez-vous sur http://localhost:3000/admin/blog pour voir vos articles.');
}

createArticles();
